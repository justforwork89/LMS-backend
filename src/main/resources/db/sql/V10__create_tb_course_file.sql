CREATE TABLE TB_COURSE_FILE (
    FILE_ID       NUMBER GENERATED ALWAYS AS IDENTITY,
    COURSE_ID     NUMBER         NOT NULL,
    ORIGIN_NAME   VARCHAR2(255)  NOT NULL,
    SAVE_NAME     VARCHAR2(100)  NOT NULL,
    FILE_PATH     VARCHAR2(300)  NOT NULL,
    FILE_SIZE     NUMBER(12)     NOT NULL,
    CONTENT_TYPE  VARCHAR2(100),
    UPLOADER_ID   VARCHAR2(30)   NOT NULL,
    REG_DT        DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_COURSE_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_COURSE_FILE_COURSE FOREIGN KEY (COURSE_ID) REFERENCES TB_COURSE (COURSE_ID),
    CONSTRAINT FK_COURSE_FILE_UPLOADER FOREIGN KEY (UPLOADER_ID) REFERENCES TB_USER (USER_ID)
);

CREATE INDEX IX_COURSE_FILE_COURSE ON TB_COURSE_FILE (COURSE_ID);