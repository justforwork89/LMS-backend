-- 과제 제출 첨부파일 (제출 1건에 파일 여러 개)
CREATE TABLE TB_SUBMISSION_FILE (
    FILE_ID        NUMBER GENERATED ALWAYS AS IDENTITY,
    SUBMISSION_ID  NUMBER         NOT NULL,
    ORIGIN_NAME    VARCHAR2(255)  NOT NULL,
    SAVE_NAME      VARCHAR2(100)  NOT NULL,
    FILE_PATH      VARCHAR2(300)  NOT NULL,
    FILE_SIZE      NUMBER(12)     NOT NULL,
    CONTENT_TYPE   VARCHAR2(100),
    REG_DT         DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_SUBMISSION_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_SUB_FILE_SUBMISSION FOREIGN KEY (SUBMISSION_ID) REFERENCES TB_SUBMISSION (SUBMISSION_ID)
);
CREATE INDEX IX_SUB_FILE_SUBMISSION ON TB_SUBMISSION_FILE (SUBMISSION_ID);