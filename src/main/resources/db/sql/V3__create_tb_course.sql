CREATE TABLE TB_COURSE (
    COURSE_ID     NUMBER GENERATED ALWAYS AS IDENTITY,
    COURSE_NAME   VARCHAR2(100)  NOT NULL,
    DESCRIPTION   VARCHAR2(2000),
    INSTRUCTOR_ID VARCHAR2(30)   NOT NULL,
    MAJOR         VARCHAR2(50)   DEFAULT '공통' NOT NULL,
    START_DATE    DATE           NOT NULL,
    END_DATE      DATE           NOT NULL,
    CAPACITY      NUMBER(5)      NOT NULL,
    ENROLLED_CNT  NUMBER(5)      DEFAULT 0 NOT NULL,
    STATUS_CD     VARCHAR2(2)    DEFAULT '10' NOT NULL,
    CONSTRAINT PK_TB_COURSE PRIMARY KEY (COURSE_ID),
    CONSTRAINT FK_COURSE_INSTRUCTOR FOREIGN KEY (INSTRUCTOR_ID) REFERENCES TB_USER (USER_ID),
    CONSTRAINT CK_COURSE_DATE CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_COURSE_CAPACITY CHECK (CAPACITY > 0 AND ENROLLED_CNT >= 0 AND ENROLLED_CNT <= CAPACITY)
);