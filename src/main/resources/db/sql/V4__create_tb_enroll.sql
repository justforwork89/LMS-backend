CREATE TABLE TB_ENROLL (
    ENROLL_ID   NUMBER GENERATED ALWAYS AS IDENTITY,
    STUDENT_ID  VARCHAR2(30) NOT NULL,
    COURSE_ID   NUMBER       NOT NULL,
    STATUS_CD   VARCHAR2(2)  DEFAULT '10' NOT NULL,
    APPLIED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TB_ENROLL PRIMARY KEY (ENROLL_ID),
    CONSTRAINT FK_ENROLL_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES TB_USER (USER_ID),
    CONSTRAINT FK_ENROLL_COURSE  FOREIGN KEY (COURSE_ID)  REFERENCES TB_COURSE (COURSE_ID),
    CONSTRAINT UK_ENROLL UNIQUE (STUDENT_ID, COURSE_ID)
);