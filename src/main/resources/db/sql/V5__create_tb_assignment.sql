CREATE TABLE TB_ASSIGNMENT (
    ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    COURSE_ID     NUMBER        NOT NULL,
    TITLE         VARCHAR2(200) NOT NULL,
    CONTENT       CLOB,
    DUE_DATE      TIMESTAMP     NOT NULL,
    CONSTRAINT PK_TB_ASSIGNMENT PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT FK_ASSIGNMENT_COURSE FOREIGN KEY (COURSE_ID) REFERENCES TB_COURSE (COURSE_ID)
);