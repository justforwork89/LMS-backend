CREATE TABLE TB_SUBMISSION (
    SUBMISSION_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    ASSIGNMENT_ID NUMBER        NOT NULL,
    STUDENT_ID    VARCHAR2(30)  NOT NULL,
    CONTENT       CLOB,
    FILE_NAME     VARCHAR2(255),
    SUBMITTED_AT  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    SCORE         NUMBER(3),
    FEEDBACK      VARCHAR2(2000),
    STATUS_CD     VARCHAR2(2)   DEFAULT '10' NOT NULL,
    CONSTRAINT PK_TB_SUBMISSION PRIMARY KEY (SUBMISSION_ID),
    CONSTRAINT FK_SUB_ASSIGNMENT FOREIGN KEY (ASSIGNMENT_ID) REFERENCES TB_ASSIGNMENT (ASSIGNMENT_ID),
    CONSTRAINT FK_SUB_STUDENT    FOREIGN KEY (STUDENT_ID)    REFERENCES TB_USER (USER_ID),
    CONSTRAINT UK_SUBMISSION UNIQUE (ASSIGNMENT_ID, STUDENT_ID),
    CONSTRAINT CK_SUB_SCORE CHECK (SCORE BETWEEN 0 AND 100)
);