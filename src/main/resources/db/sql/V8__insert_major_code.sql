-- 전공 공통코드. 화면(공통코드 관리)으로 이미 등록한 DB에서도 실패하지 않도록 없는 행만 넣는다.
MERGE INTO TB_COMMON_CODE t
USING (
    SELECT 'MAJOR' AS GROUP_CD, '10' AS CODE, '컴퓨터공학' AS CODE_NAME, 1 AS SORT_ORDER FROM DUAL UNION ALL
    SELECT 'MAJOR', '20', '정보보안', 2 FROM DUAL UNION ALL
    SELECT 'MAJOR', '30', '데이터분석', 3 FROM DUAL UNION ALL
    SELECT 'MAJOR', '40', '공통', 4 FROM DUAL
) s
ON (t.GROUP_CD = s.GROUP_CD AND t.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (GROUP_CD, CODE, CODE_NAME, SORT_ORDER) VALUES (s.GROUP_CD, s.CODE, s.CODE_NAME, s.SORT_ORDER);
